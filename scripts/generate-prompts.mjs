// Generates src/server/prompts.generated.ts from the repo markdown.
//
// The markdown stays the single source of truth; this runs before dev/build so
// a missing or renamed skill fails the build instead of 404ing at runtime.
import { readFileSync, writeFileSync } from "node:fs"

const FILES = {
  persona: "docs/agents/persona.md",
  "forge-npc": ".agents/skills/forge-npc/SKILL.md",
  "forge-location": ".agents/skills/forge-location/SKILL.md",
  "forge-religion": ".agents/skills/forge-religion/SKILL.md",
  "plan-story-arc": ".agents/skills/plan-story-arc/SKILL.md",
  "arc-template": "Campaign/Planning/_Template.md",
  web: "docs/agents/channels/web.md",
}

function stripFrontmatter(md) {
  return md.replace(/^\uFEFF?---\r?\n[\s\S]*?\r?\n---\r?\n?/, "")
}

const entries = Object.entries(FILES).map(([key, path]) => {
  const content = stripFrontmatter(readFileSync(path, "utf8"))
  return `  ${JSON.stringify(key)}: ${JSON.stringify(content)},`
})

const output = `// Generated by scripts/generate-prompts.mjs. Do not edit by hand.

export const PROMPTS = {
${entries.join("\n")}
} as const

export type PromptKey = keyof typeof PROMPTS
`

writeFileSync("src/server/prompts.generated.ts", output)
